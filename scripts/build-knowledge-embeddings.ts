/**
 * Builds src/lib/knowledge-embeddings.json — one Gemini embedding per knowledge chunk.
 *
 *   npm run build:knowledge
 *
 * RE-RUN THIS (and commit the JSON) WHENEVER YOU CHANGE the data files the chunks come from:
 * src/data/portfolio.ts, projects.ts, experience.ts, achievements.ts. Until you do, edited/new chunks are simply
 * included in every answer (so nothing is lost), but they cannot be ranked by relevance.
 *
 * Uses GEMINI_API_KEY from the environment or from .env.local (the same key the chat route uses).
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { EMBED_DIMS, EMBED_MODEL, embedTexts } from "../src/lib/embeddings";
import { buildChunks, chunkHash, embeddingText } from "../src/lib/portfolioKnowledge";

const root = process.cwd();

// tiny .env.local reader, so the script needs no extra dependency or Node flags
if (!process.env.GEMINI_API_KEY) {
  const envFile = join(root, ".env.local");
  if (existsSync(envFile)) {
    for (const line of readFileSync(envFile, "utf8").split(/\r?\n/)) {
      const m = line.match(/^\s*GEMINI_API_KEY\s*=\s*(.*)\s*$/);
      if (m) process.env.GEMINI_API_KEY = m[1].replace(/^["']|["']$/g, "").trim();
    }
  }
}
if (!process.env.GEMINI_API_KEY) {
  console.error("GEMINI_API_KEY is missing. Put it in .env.local (see .env.example) and run again.");
  process.exit(1);
}

async function main() {
  // the pinned "portfolio map" is always sent as-is, so it needs no embedding
  const chunks = buildChunks().filter((c) => c.kind !== "map");
  console.log(`Embedding ${chunks.length} chunks with ${EMBED_MODEL} (${EMBED_DIMS} dimensions)…`);

  const vectors = await embedTexts(chunks.map(embeddingText), "RETRIEVAL_DOCUMENT");

  const out = {
    model: EMBED_MODEL,
    dimensions: EMBED_DIMS,
    createdAt: new Date().toISOString(),
    note: "Generated by `npm run build:knowledge` from the data files. Do not edit by hand.",
    chunks: chunks.map((c, i) => ({
      id: c.id,
      kind: c.kind,
      title: c.title,
      text: c.text,
      hash: chunkHash(c),
      embedding: vectors[i].map((x) => Math.round(x * 1e5) / 1e5),
    })),
  };

  const file = join(root, "src", "lib", "knowledge-embeddings.json");
  writeFileSync(file, JSON.stringify(out));
  console.log(`Wrote ${chunks.length} chunks to src/lib/knowledge-embeddings.json (${Math.round(JSON.stringify(out).length / 1024)} KB).`);
}

main().catch((err) => {
  console.error("Failed:", err instanceof Error ? err.message : err);
  process.exit(1);
});
